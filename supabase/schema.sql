-- Run ONLY in a NEW empty project. No personal records or seed data included.
-- This is PostgreSQL DDL; the existing Drizzle SQLite schema is for shared
-- TypeScript types/validation, not the deployment database.
begin;
create table public.jobs (
  id bigint generated by default as identity primary key,
  company text not null,
  role text not null,
  status text not null default 'Interested'
    check (status in ('Interested','Applied','Phone Screen','Interview','Offer','Rejected','Withdrawn')),
  location text, url text,
  salary_base text, salary_rsu text, salary_bonus text, salary_total text,
  rto_days integer, rto_notes text, source text,
  applied_at date, posted_at date,
  priority integer not null default 2,
  notes text, next_steps text, glassdoor_rating text, blind_rating text,
  relevance_score integer, relevance_summary text,
  deleted_at timestamptz,
  created_at timestamptz not null default now()
);
create table public.contacts (
  id bigint generated by default as identity primary key,
  job_id bigint not null references public.jobs(id) on delete cascade,
  name text not null,
  role text, email text, linkedin text, notes text
);
create table public.action_items (
  id bigint generated by default as identity primary key,
  job_id bigint not null references public.jobs(id) on delete cascade,
  text text not null,
  done integer not null default 0 check (done in (0,1)),
  created_at timestamptz not null default now()
);
create index contacts_job_id_idx on public.contacts(job_id);
create index action_items_job_id_idx on public.action_items(job_id);
alter table public.jobs enable row level security;
alter table public.contacts enable row level security;
alter table public.action_items enable row level security;
-- No public/anon/authenticated policies. Only the server's privileged key
-- should access these tables; do not expose that key in frontend variables.
revoke all on public.jobs, public.contacts, public.action_items from anon, authenticated;
grant all on public.jobs, public.contacts, public.action_items to service_role;
grant usage, select on all sequences in schema public to service_role;
commit;
